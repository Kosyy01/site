function setupMusicPlayer(){
  const player=$('#music-player'), main=$('#audio-song-1'), second=$('#audio-song-2');
  if(!player||!main||!second)return;
  const tracks=[
    {audio:main,title:'I Thought I Saw Your Face Today',artist:'Główna piosenka'},
    {audio:second,title:'Perfect — Ed Sheeran',artist:'Druga piosenka'}
  ];
  let active=0;
  const title=$('#music-title'), artist=$('#music-artist'), toggle=$('#music-main-toggle');
  const fmt=s=>Number.isFinite(s)?`${Math.floor(s/60)}:${String(Math.floor(s%60)).padStart(2,'0')}`:'0:00';
  const setIcon=()=>{toggle.innerHTML=`<i data-lucide="${tracks[active].audio.paused?'play':'pause'}"></i>`;refreshIcons()};
  const sync=()=>{const a=tracks[active].audio;$('#music-current').textContent=fmt(a.currentTime);$('#music-duration').textContent=fmt(a.duration);$('#music-progress').value=a.duration?(a.currentTime/a.duration)*100:0;setIcon()};
  const play=async(i)=>{
    active=i;
    tracks.forEach((t,n)=>{if(n!==i)t.audio.pause()});
    title.textContent=tracks[i].title; artist.textContent=tracks[i].artist;
    $$('.music-track').forEach((b,n)=>b.classList.toggle('active',n===i));
    try{await tracks[i].audio.play()}catch(err){console.warn('Autoplay/play blocked',err)}
    sync();
  };
  const select=i=>play(i);
  toggle.addEventListener('click',e=>{e.stopPropagation();const a=tracks[active].audio;if(a.paused)play(active);else{a.pause();sync()}});
  $$('.music-track').forEach(btn=>btn.addEventListener('click',e=>{e.stopPropagation();select(+btn.dataset.track)}));
  $('#music-progress').addEventListener('input',e=>{const a=tracks[active].audio;if(a.duration)a.currentTime=a.duration*(+e.target.value/100)});
  tracks.forEach((t,i)=>{
    ['timeupdate','loadedmetadata','durationchange','play','pause'].forEach(ev=>t.audio.addEventListener(ev,sync));
    t.audio.addEventListener('ended',()=>{if(i===active)play((i+1)%tracks.length)});
    t.audio.addEventListener('error',()=>console.warn('Missing/unreadable audio:',t.audio.src));
  });
  $('#music-minimize').addEventListener('click',e=>{e.stopPropagation();player.classList.toggle('minimized')});
  player.addEventListener('click',e=>{
    if(player.classList.contains('minimized') && !e.target.closest('#music-minimize')) player.classList.remove('minimized');
  });
  // SONG 1: strongest possible autoplay strategy.
  // Browsers may still block unmuted autoplay until a user gesture; we retry on
  // every lifecycle event and the first interaction without requiring the player button.
  main.autoplay = true;
  main.preload = 'auto';
  main.loop = false;
  second.preload = 'auto';

  const startSong1 = async () => {
    if (active !== 0 && !main.paused) return;
    active = 0;
    second.pause();
    main.currentTime = main.currentTime || 0;
    title.textContent = tracks[0].title;
    artist.textContent = tracks[0].artist;
    $$('.music-track').forEach((b,n)=>b.classList.toggle('active',n===0));
    try {
      main.muted = false;
      main.volume = 1;
      await main.play();
    } catch (err) {
      // A muted start is allowed by more browsers. If it starts, we immediately
      // try to restore sound on the next permitted user interaction.
      try { main.muted = true; await main.play(); } catch (_) {}
    }
    sync();
  };

  startSong1();
  window.addEventListener('load', startSong1, {once:true});
  window.addEventListener('pageshow', startSong1);
  document.addEventListener('visibilitychange',()=>{if(!document.hidden && main.paused) startSong1()});

  const unlockAutoplay = () => {
    if (main.muted) main.muted = false;
    if (main.paused) startSong1();
    else sync();
    document.removeEventListener('pointerdown', unlockAutoplay, true);
    document.removeEventListener('touchstart', unlockAutoplay, true);
    document.removeEventListener('keydown', unlockAutoplay, true);
  };
  document.addEventListener('pointerdown', unlockAutoplay, true);
  document.addEventListener('touchstart', unlockAutoplay, true);
  document.addEventListener('keydown', unlockAutoplay, true);
  sync();
}
